<?php

/*
 * إعدادات المساعد الذكي — «اسأل السيستم» ومسح الفواتير.
 *
 * المزوّد بيتبدّل من .env لوحده: ERP_AI_PROVIDER=gemini أو anthropic.
 * مفاتيح الـ API بتتقرا من إعدادات Prism نفسها (GEMINI_API_KEY /
 * ANTHROPIC_API_KEY) وعمرها ما بتوصل للمتصفح — كل النداءات من السيرفر.
 *
 * الاستضافة مشتركة (exec و proc_open مقفولين، ومفيش Node)، وحد تنفيذ
 * PHP حوالي 30 ثانية — فكل النداءات HTTP عادي من غير streaming، وفيه
 * ميزانية وقت صارمة تحت عشان الرد يوصل قبل ما PHP يقطع.
 */

$provider = env('ERP_AI_PROVIDER', 'gemini');

/*
 * موديل افتراضي لكل مزوّد.
 *
 * المحادثة على flash-lite عن قصد: بالقياس على السيرفر الفعلي، النداء
 * الواحد على flash بياخد حوالي 14 ثانية وعلى flash-lite أقل من ثانية.
 * وسؤال زي «مين أكبر مديونية؟» الفرق في جودة الرد بينهم مش محسوس،
 * لأن الرقم جاي من الأداة أصلاً مش من الموديل. أربعتاشر ثانية للنداء
 * الواحد يعني سؤال بجولة أدوات واحدة بياكل الميزانية كلها.
 *
 * قراءة الفواتير فضلت على flash: صورة خط إيد مايلة محتاجة الموديل
 * الأكبر، والمسح نداء واحد مش دورة، فالـ 14 ثانية مقبولة فيه.
 *
 * (gemini-2.5-flash بقى بيرجّع 404 للحسابات الجديدة، فما ينفعش يبقى
 * افتراضي.) وHaiku أرخص موديلات Anthropic.
 */
/*
 * **البديل لازم يبقى موديل تاني غير الأساسي.**
 *
 * ده مش تفضيل، ده شرط. البديل بيتجرّب لما الأساسي يرجّع 503 (مزحوم)،
 * ونفس الموديل المزحوم هيرجّع 503 تاني — فبديل بنفس اسم الأساسي معناه
 * إن مفيش بديل أصلاً.
 *
 * وده اللي حصل على السيرفر: المحادثة والبديل الاتنين كانوا
 * `gemini-3.5-flash-lite`، فلما الموديل اتزحم، التلات محاولات كلها
 * راحت لنفس الموديل المزحوم ووقعت ورا بعض، والمستخدم شاف «المساعد مش
 * متاح» من غير ما يكون فيه أي محاولة حقيقية على موديل تاني.
 *
 * `alternates` هي شبكة الأمان: لو البديل اتظبط من `.env` بنفس اسم
 * الأساسي، `AiService` بياخد أول واحد في القايمة دي مختلف عنه.
 */
$defaults = [
    'gemini' => [
        'chat' => 'gemini-3.5-flash-lite',
        'vision' => 'gemini-3.5-flash',
        // جيل أقدم ومستقر — مش نفس الموديل اللي بيتزحم
        'fallback' => 'gemini-3.1-flash-lite',
        // التوجيه: تصنيف كلمة واحدة، أخف حاجة موجودة
        'routing' => 'gemini-3.5-flash-lite',
        'alternates' => ['gemini-3.1-flash-lite', 'gemini-3.5-flash'],
    ],
    'anthropic' => [
        'chat' => 'claude-haiku-4-5',
        'vision' => 'claude-haiku-4-5',
        // أكبر من Haiku، بس مابيتستعملش غير لما Haiku يزحم أو يتأخر
        'fallback' => 'claude-sonnet-5',
        'routing' => 'claude-haiku-4-5',
        'alternates' => ['claude-sonnet-5', 'claude-haiku-4-5'],
    ],
];

$default = $defaults[$provider] ?? $defaults['gemini'];

return [
    /* قفل المساعد كله — زرار «اسأل السيستم» و«مسح فاتورة» بيختفوا لو false */
    'enabled' => env('ERP_AI_ENABLED', true),

    'provider' => $provider,

    'models' => [
        // المحادثة — محتاج استدعاء أدوات
        'chat' => env('ERP_AI_CHAT_MODEL', $default['chat']),
        // قراءة صور الفواتير و PDF — محتاج رؤية ومخرجات JSON متقيّدة
        'vision' => env('ERP_AI_VISION_MODEL', $default['vision']),
        // بديل بيتجرّب لو الأساسي مزحوم (503) أو مش موجود (404)
        'fallback' => env('ERP_AI_FALLBACK_MODEL', $default['fallback']),
        // التوجيه — نداء تصنيف صغير قبل الإجابة
        'routing' => env('ERP_AI_ROUTING_MODEL', $default['routing']),
        /*
         * بدائل احتياطية — بيتاخد منها أول واحد مختلف عن الأساسي لو
         * `ERP_AI_FALLBACK_MODEL` اتظبط بنفس اسمه.
         */
        'alternates' => $default['alternates'],
    ],

    'max_tokens' => (int) env('ERP_AI_MAX_TOKENS', 2048),

    /*
     * الوقت — ده اللي بيخلّي الشاشة ما تعلّقش على استضافة مشتركة.
     *
     * timeout: أقصى وقت لنداء HTTP واحد للمزوّد.
     * budget: أقصى وقت للطلب كله بما فيه جولات الأدوات. لازم يفضل
     *         تحت حد تنفيذ PHP (حوالي 30 ثانية) عشان المستخدم يشوف
     *         رسالة عربية مفهومة بدل صفحة 500 بيضا.
     */
    'timeout' => (int) env('ERP_AI_TIMEOUT', 20),
    'budget' => (int) env('ERP_AI_BUDGET', 25),

    /*
     * أقصى عدد جولات أدوات في سؤال واحد. المساعد ساعات بيحتاج أداتين
     * (رصيد تاجر + فواتيره مثلًا) قبل ما يرد. الميزانية فوق هي الحكم
     * الحقيقي — الرقم ده سقف إضافي.
     */
    'max_steps' => (int) env('ERP_AI_MAX_STEPS', 3),

    /*
     * ميزانية التفكير.
     *
     * أسئلة المحادثة مباشرة («مين أكبر مديونية؟») — التفكير العميق فيها
     * بيضيّع تانية على تانية من غير فايدة، فبنخليه أقل حاجة المزوّد
     * بيسمح بيها. قراءة الفاتورة عكس كده: صورة مزحومة وأرقام، فبنسيب
     * التفكير على وضعه الطبيعي.
     *
     * Gemini 3.x بياخد thinkingLevel (low/high)، و2.5 بياخد
     * thinkingBudget بالتوكنز. Anthropic ما بيفكّرش أصلًا غير لما
     * تطلب منه، فالفاضي هنا هو الأقل عنده.
     */
    'thinking' => [
        'gemini' => [
            'chat' => ['thinkingLevel' => env('ERP_AI_CHAT_THINKING', 'low')],
            'vision' => [],
            'route' => ['thinkingLevel' => 'low'],
        ],
        'anthropic' => [
            'chat' => [],
            'vision' => [],
            'route' => [],
        ],
    ],

    /*
     * توجيه السؤال.
     *
     * قبل الإجابة بنسأل الموديل الخفيف سؤال واحد: السؤال ده بيخص أنهي
     * مجال؟ وبنبعت أدوات المجالات دي بس. السبب إن وصف كل أداة بيتبعت
     * مع كل جولة — تمنتاشر أداة في السلّة معناها تعليمات أطول ووقت
     * أطول واحتمال أكبر إنه يختار الأداة الغلط.
     *
     * timeout: سقف نداء التوجيه لوحده. التصنيف جملة واحدة، فلو أخد
     *          أكتر من كده يبقى في حاجة غلط والأحسن نكمّل بالافتراضي.
     * reserve: أقل وقت فاضل من الميزانية يستاهل إننا ننفق منه على
     *          توجيه. أقل من كده بنروح على المجموعة الافتراضية على
     *          طول — الإجابة أهم من دقة التوجيه.
     */
    'routing' => [
        'timeout' => (int) env('ERP_AI_ROUTING_TIMEOUT', 6),
        'reserve' => (int) env('ERP_AI_ROUTING_RESERVE', 10),
    ],

    /* حد الاستخدام لكل مستخدم في الدقيقة */
    'rate_limits' => [
        'chat' => (int) env('ERP_AI_CHAT_RATE_LIMIT', 20),
        'scan' => (int) env('ERP_AI_SCAN_RATE_LIMIT', 6),
    ],

    /*
     * أقصى عدد رسايل بتتحفظ في الجلسة.
     *
     * كل رسالة زيادة = توكنز زيادة = وقت زيادة، والوقت هو المشكلة هنا،
     * فبنمسك آخر 6 بس (٣ أسئلة وردودها) — كفاية لسؤال متابعة.
     */
    'history_limit' => (int) env('ERP_AI_HISTORY_LIMIT', 6),

    /*
     * عدد الأسئلة المقترحة في اللوحة وهي فاضية.
     *
     * الأسئلة نفسها جاية من الوكلاء في `app/Ai/Agents` — مخلوطة من كل
     * المجالات اللي دور المستخدم بيوصلها، عشان اللوحة تقول له من أول
     * نظرة إنها بتجاوب على أي حاجة مش على مجال واحد.
     */
    'starters_limit' => (int) env('ERP_AI_STARTERS', 6),
];
