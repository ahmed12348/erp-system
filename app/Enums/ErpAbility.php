<?php

namespace App\Enums;

/**
 * صلاحيات النظام — كل صلاحية بتترجم لـ Gate بنفس الاسم.
 *
 * القاعدة بسيطة: البيانات الأساسية (مخازن، تصنيفات، أصناف، موردين، تجار،
 * مندوبين) بيديرها المدير والمحاسب، والمبيعات بيشوفوا بس. المستخدمين
 * والأدوار للمدير لوحده.
 */
enum ErpAbility: string
{
    /** إنشاء وتعديل وإيقاف البيانات الأساسية */
    case ManageMasterData = 'master-data:manage';

    /** إضافة صنف سريع من جوه فاتورة الشراء — من غير باقي صلاحيات الأصناف */
    case QuickAddProduct = 'product:quick-add';

    /**
     * فتح طلبات التحضير وتحضيرها وإلغاؤها.
     *
     * المبيعات ليهم الصلاحية دي — الطلب بيتفتح وهو واقف مع التاجر،
     * ومفيهوش أسعار أصلاً فمفيش حاجة حسّاسة بتتكشف.
     */
    case ManagePreparationOrders = 'preparation-orders:manage';

    /** إدارة المستخدمين وأدوارهم */
    case ManageUsers = 'users:manage';
}
